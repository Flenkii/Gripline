# Generates files.h: the installer files the .exe carries, as byte arrays.
# Usage: python3 embed.py <fh1-lite folder> <out.h>
import sys, os
root, out = sys.argv[1], sys.argv[2]
files = ["installer/GriplineLite.ps1", "installer/logo.png"] + [
    "src/hooks/" + f for f in ("gripline_settings.h", "gripline_wheel.cpp", "gripline_dashcam.cpp",
                               "gripline_menu.cpp", "gripline_traffic.cpp")]
with open(out, "w") as h:
    h.write("// Generated by embed.py, do not edit.\n")
    for i, f in enumerate(files):
        data = open(os.path.join(root, f), "rb").read()
        h.write("static const unsigned char f%d[] = {%s};\n" % (i, ",".join(str(b) for b in data)))
    h.write("static const struct { const wchar_t* path; const unsigned char* data; unsigned size; } kFiles[] = {\n")
    for i, f in enumerate(files):
        h.write('  {L"%s", f%d, sizeof(f%d)},\n' % (f.replace("/", "\\\\"), i, i))
    h.write("};\n")
